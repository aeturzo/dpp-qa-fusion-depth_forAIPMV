#!/usr/bin/env python3
"""Exploratory re-reporting of the locked verified-subset results.

READ-ONLY. Touches nothing outside this folder: it reads the locked eval CSVs
and writes one markdown report next to itself. It does not modify the
artifacts, the benchmark, make_numbers.py, or the paper.

Purpose: three properties of the released grading were found while building the
qualitative example table, and each one moves the headline numbers. This script
quantifies them so the paper can either correct for them or state them.

  P1  scope   173 of 2,649 "logic" rows ask about the ontology's own vocabulary
              (Is decimal a Datatype?) or whether a bare measurement is a class
              instance (Is 18 V a Thing?). Neither is a product-passport
              question, and the baselines' context never contained the OWL
              metamodel.
  P2  abstain the grader scores an explicit refusal as a wrong answer. LINC
              emits INSUFFICIENT 168 times and an underived premise list 126
              times; both count as errors.
  P3  leakage a premise dump can contain the gold substring by accident
              (gold "Class" vs premise "ex:Product a rdfs:Class"), so some
              non-answers are scored CORRECT.

Usage:  python analysis_clean.py
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
LOCKED = REPO / "artifacts" / "locked_results" / "verified_v1_20260521_173612_CEST"
OUT = HERE / "CLEAN_REPORT.md"

SYSTEM = "ADAPTIVERAG"
FILES = {
    "LongCtx": "eval_GPT4O_LONGCTX_verified_v1.csv",
    "LINC": "eval_LINC_verified_v1.csv",
    "LogicLM": "eval_LOGIC_LM_verified_v1.csv",
    "System": "eval_ADAPTIVERAG_verified_v1_full.csv",
}
ORDER = ["LongCtx", "LINC", "LogicLM", "System"]
KEY = ["id", "query"]  # id alone is NOT unique: 449 duplicates


def load() -> pd.DataFrame:
    base = None
    for name in ORDER:
        d = pd.read_csv(LOCKED / FILES[name])[KEY + ["type", "domain", "answer",
                                                     "correct", "expected_contains"]]
        d = d.rename(columns={"answer": f"ans_{name}", "correct": f"ok_{name}"})
        if base is None:
            base = d
        else:
            base = base.merge(d.drop(columns=["type", "domain", "expected_contains"]),
                              on=KEY)
    assert len(base) == 6270, len(base)
    return base


def is_out_of_scope(q: str) -> bool:
    """Ontology-vocabulary or bare-measurement class membership."""
    return bool(re.search(r"a (?:Datatype|AnnotationProperty|Class)\?$", q)
                or re.match(r"^Is [0-9]", q))


def is_abstention(ans: str) -> bool:
    """An explicit refusal, or a returned premise list with no derived answer."""
    a = str(ans).strip()
    return (a.upper().startswith("INSUFFICIENT")
            or a.startswith("Premises:")
            or bool(re.match(r"^(cannot determine|not enough|unknown)", a, re.I)))


def pct(x) -> str:
    return f"{100 * float(x):.2f}"


def main() -> int:
    m = load()
    m["oos"] = m["query"].map(is_out_of_scope)
    for n in ORDER:
        m[f"abst_{n}"] = m[f"ans_{n}"].map(is_abstention)
        m[f"ok_{n}"] = m[f"ok_{n}"].astype(bool)

    L = []
    w = L.append
    w("# Clean re-report of the verified subset\n")
    w("Exploratory. Read-only over the locked artifacts; nothing else was "
      "changed. Generated by `analysis_clean.py`.\n")

    # ---------- P1 scope ----------
    logic = m["type"] == "logic"
    w(f"\n## P1. Scope of the `logic` type\n")
    w(f"`logic` rows: **{int(logic.sum()):,}**, of which out-of-scope: "
      f"**{int((logic & m['oos']).sum())}** "
      f"({100 * (logic & m['oos']).sum() / logic.sum():.1f}%).\n")
    w("\nNone of the 88 distinct `logic` templates contains a threshold, limit, "
      "or compliance comparison. All are class-membership queries.\n")

    def grp(q):
        if re.search(r"a (?:Datatype|AnnotationProperty|Class)\?$", q):
            return "ontology vocabulary"
        if re.match(r"^Is [0-9]", q):
            return "bare measurement"
        return "product classification"

    g = m[logic].copy()
    g["grp"] = g["query"].map(grp)
    w("\n| logic subset | n | " + " | ".join(ORDER) + " |")
    w("|---|---|" + "---|" * len(ORDER))
    for name, s in g.groupby("grp"):
        w(f"| {name} | {len(s):,} | "
          + " | ".join(pct(s[f'ok_{n}'].mean()) for n in ORDER) + " |")

    # ---------- P2 abstention ----------
    w("\n\n## P2. Abstentions scored as wrong answers\n")
    w("\n| system | errors | of which abstentions | substantive errors |")
    w("|---|---|---|---|")
    for n in ORDER:
        err = ~m[f"ok_{n}"]
        ab = err & m[f"abst_{n}"]
        w(f"| {n} | {int(err.sum()):,} | {int(ab.sum()):,} "
          f"({100 * ab.sum() / max(err.sum(), 1):.0f}%) | "
          f"{int((err & ~m[f'abst_{n}']).sum()):,} |")

    # ---------- P3 leakage ----------
    w("\n\n## P3. Non-answers scored as correct\n")
    w("\n| system | abstentions | graded CORRECT |")
    w("|---|---|---|")
    for n in ORDER:
        ab = m[f"abst_{n}"]
        w(f"| {n} | {int(ab.sum()):,} | {int((ab & m[f'ok_{n}']).sum()):,} |")

    # ---------- corrected views ----------
    keep = ~m["oos"]
    w("\n\n## Corrected accuracy\n")
    w("\n**A. As published.**\n")
    w("\n| system | recall | open | rule | overall |")
    w("|---|---|---|---|---|")
    for n in ORDER:
        row = [pct(m[m['type'] == t][f'ok_{n}'].mean()) for t in ("recall", "open", "logic")]
        w(f"| {n} | " + " | ".join(row) + f" | {pct(m[f'ok_{n}'].mean())} |")

    w("\n**B. Out-of-scope logic rows removed "
      f"({int(m['oos'].sum())} rows, {int(keep.sum()):,} remain).**\n")
    w("\n| system | recall | open | rule | overall |")
    w("|---|---|---|---|---|")
    for n in ORDER:
        row = [pct(m[keep & (m['type'] == t)][f'ok_{n}'].mean())
               for t in ("recall", "open", "logic")]
        w(f"| {n} | " + " | ".join(row) + f" | {pct(m[keep][f'ok_{n}'].mean())} |")

    w("\n**C. Out-of-scope removed, and abstentions excluded from the "
      "denominator (selective view: accuracy when the system chose to answer, "
      "with coverage).**\n")
    w("\n| system | coverage | accuracy when answered | recall | open | rule |")
    w("|---|---|---|---|---|---|")
    for n in ORDER:
        sub = m[keep]
        ans = ~sub[f"abst_{n}"]
        cov = ans.mean()
        acc = sub[ans][f"ok_{n}"].mean()
        per = []
        for t in ("recall", "open", "logic"):
            s2 = sub[(sub["type"] == t) & ans]
            per.append(pct(s2[f"ok_{n}"].mean()) if len(s2) else "--")
        w(f"| {n} | {100 * cov:.1f} | {pct(acc)} | " + " | ".join(per) + " |")

    # ---------- headroom ----------
    w("\n\n## Headroom to the ceiling, by view\n")
    w("\n| view | recall | open | rule | monotone? |")
    w("|---|---|---|---|---|")
    for label, mask in [("A. as published", pd.Series(True, index=m.index)),
                        ("B. out-of-scope removed", keep)]:
        hs = []
        for t in ("recall", "open", "logic"):
            s = m[mask & (m["type"] == t)]
            best = max(s[f"ok_{n}"].mean() for n in ORDER if n != "System")
            hs.append(100 * (s["ok_System"].mean() - best))
        w(f"| {label} | " + " | ".join(f"{h:.2f}" for h in hs) + " | "
          + ("yes" if hs == sorted(hs) else "**no**") + " |")

    # ---------- discordance ----------
    w("\n\n## Paired discordance, both views\n")
    w("\n| baseline | view | system-only correct | baseline-only correct |")
    w("|---|---|---|---|")
    for n in ORDER[:3]:
        for label, mask in [("as published", pd.Series(True, index=m.index)),
                            ("out-of-scope removed", keep)]:
            s = m[mask]
            w(f"| {n} | {label} | {int((s['ok_System'] & ~s[f'ok_{n}']).sum()):,} "
              f"| {int((~s['ok_System'] & s[f'ok_{n}']).sum())} |")

    OUT.write_text("\n".join(L) + "\n")
    print(f"written -> {OUT}")
    print("\n".join(L[-40:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
